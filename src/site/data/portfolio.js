const sentence = (value = "") => value.replace(/&amp;/g, "&");
const toWords = (value = "") => sentence(value).split(",").map((part) => part.trim()).filter(Boolean);
const primaryCategory = (value = "") => toWords(value)[0] || "productivity";
const labelFor = (value = "") => categoryLabelMap[value] || "Digital Product";
const slugify = (value = "") => value.toLowerCase().replace(/&/g, "and").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");

const servicesFor = (category, source) => {
  const base = ["Product Strategy", "UX Systems", "Launch Support"];
  if (category.includes("artificial-intelligence") || category.includes("voice-ai")) return ["AI Development", "Workflow Automation", "Product Engineering"];
  if (category.includes("health") || category.includes("wellness")) return ["iOS Development", "Backend Systems", "Product Design"];
  if (category.includes("real-estate") || category.includes("finance") || category.includes("crm")) return ["Mobile App Development", "Automation", "Dashboard Systems"];
  if (category.includes("games") || category.includes("entertainment") || category.includes("streaming")) return ["Mobile App Development", "Engagement UX", "Release Engineering"];
  return source === "exyte" ? ["iOS Development", "Product Design", "Frontend Engineering"] : base;
};

